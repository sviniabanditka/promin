let currentLang: Lang = DEFAULT_LANG;

function isLang(value: string | null): value is Lang {
  return value === 'uk' || value === 'ru' || value === 'en';
}

export function initI18n(): void {
  let stored: string | null = null;
  try {
    stored = window.localStorage.getItem(STORAGE_KEY);
  } catch (e) {
    stored = null;
  }
  if (isLang(stored)) {
    currentLang = stored;
  } else {
    const nav = (window.navigator && window.navigator.language ? window.navigator.language : '').slice(0, 2);
    currentLang = isLang(nav) ? (nav as Lang) : DEFAULT_LANG;
  }
}

export function getLang(): Lang {
  return currentLang;
}

export function setLang(lang: Lang): void {
  currentLang = lang;
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
  } catch (e) {
    // storage unavailable/full: language just won't persist across sessions
  }
}

export function t(key: string, params?: { [key: string]: string | number }): string {
  const dict = dictionaries[currentLang] || dictionaries[DEFAULT_LANG];
  let str = dict[key] || key;
  if (params) {
    for (const paramKey in params) {
      if (Object.prototype.hasOwnProperty.call(params, paramKey)) {
        str = str.split('{' + paramKey + '}').join(String(params[paramKey]));
      }
    }
  }
  return str;
}
